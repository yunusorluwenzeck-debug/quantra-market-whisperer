function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="sv" className="dark" suppressHydrationWarning>
      <head>
        <HeadContent />
        <script dangerouslySetInnerHTML={{ __html: "try{if(localStorage.getItem('theme')==='light')document.documentElement.classList.remove('dark')}catch(e){}" }} />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
      if (event === "SIGNED_IN" && !sessionStorage.getItem("signin-logged")) {
        sessionStorage.setItem("signin-logged", "1");
        void import("@/lib/security.functions").then((m) => m.recordSignIn()).catch(() => {});
      }
      if (event === "SIGNED_IN") {
        const next = sessionStorage.getItem("post-auth");
        if (next && next.startsWith("/") && !next.startsWith("//")) {
          sessionStorage.removeItem("post-auth");
          void router.navigate({ href: next });
        }
      }
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AppShell>
        <Outlet />
      </AppShell>
      <Toaster />
    </QueryClientProvider>
  );
}
